IF DB_ID('FinanceDb') IS NULL CREATE DATABASE FinanceDb;
GO
USE FinanceDb;
GO
CREATE TABLE Users(Id INT IDENTITY PRIMARY KEY, Name NVARCHAR(100) NOT NULL, Email NVARCHAR(150) NOT NULL UNIQUE,
  Phone NVARCHAR(20) NOT NULL UNIQUE, PasswordHash NVARCHAR(200) NOT NULL, CreatedOn DATETIME2 DEFAULT SYSDATETIME());
CREATE TABLE Clients(Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id), Name NVARCHAR(100) NOT NULL,
  Gender NVARCHAR(10), Mobile NVARCHAR(20), Address NVARCHAR(300), PhotoPath NVARCHAR(300),
  Status NVARCHAR(10) NOT NULL DEFAULT 'Active', IsDeleted BIT NOT NULL DEFAULT 0, CreatedOn DATETIME2 DEFAULT SYSDATETIME());
CREATE TABLE Loans(Id INT IDENTITY PRIMARY KEY, UserId INT NOT NULL REFERENCES Users(Id), ClientId INT NOT NULL REFERENCES Clients(Id),
  Principal DECIMAL(18,2) NOT NULL, InterestPercent DECIMAL(5,2) NOT NULL, LoanDate DATE NOT NULL DEFAULT CAST(GETDATE() AS DATE),
  DueDate DATE NOT NULL, PenaltyPerDay DECIMAL(18,2) NOT NULL DEFAULT 0, Status NVARCHAR(10) NOT NULL DEFAULT 'Active', ClearedOn DATETIME2 NULL);
CREATE TABLE Documents(Id INT IDENTITY PRIMARY KEY, ClientId INT NOT NULL REFERENCES Clients(Id), DocType NVARCHAR(50) NOT NULL,
  FilePath NVARCHAR(300) NOT NULL, UploadedOn DATETIME2 DEFAULT SYSDATETIME());
GO
